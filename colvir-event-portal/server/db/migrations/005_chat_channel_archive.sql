-- ---------------------------------------------------------------------------
-- Тематические группы в чате.
--
-- Каналы появились еще в миграции 004, но в интерфейсе был только общий. Теперь
-- администратор заводит группы по интересам, а войти в любую может каждый —
-- закрытых каналов нет, поэтому таблица участников не нужна.
--
-- Удаление канала здесь намеренно не используется: внешний ключ chat_messages
-- стоит с ON DELETE CASCADE, то есть удаление унесло бы вместе с каналом всю
-- переписку. Вместо этого archived_at — канал пропадает из списка, история
-- остается в базе.
-- ---------------------------------------------------------------------------

ALTER TABLE chat_channels
  ADD COLUMN IF NOT EXISTS description text NOT NULL DEFAULT '';

ALTER TABLE chat_channels
  ADD COLUMN IF NOT EXISTS archived_at timestamptz;

-- Список каналов запрашивается на каждой загрузке приложения, поэтому активные
-- отбираются по частичному индексу, а не перебором всей таблицы.
CREATE INDEX IF NOT EXISTS chat_channels_active_idx
  ON chat_channels (created_at, id)
  WHERE archived_at IS NULL;

-- Общий канал закрывать нельзя: в него уходят сообщения, если канал не указан.
-- Страховка на случай, если кто-то заархивирует его напрямую в базе.
UPDATE chat_channels SET archived_at = NULL WHERE id = 'general';
