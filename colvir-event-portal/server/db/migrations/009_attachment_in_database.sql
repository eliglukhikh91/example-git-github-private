-- ---------------------------------------------------------------------------
-- Вариант хранения вложений прямо в базе.
--
-- Основной способ остается прежним — файлы на диске, в базе только метаданные:
-- для корпоративного сервера это правильно, потому что двадцатимегабайтные
-- картинки не раздувают дампы и не тянутся вместе с текстом сообщений.
--
-- Но на бесплатных хостингах постоянного диска обычно нет: файловая система
-- сбрасывается при каждом перезапуске, и картинки в чате пропадали бы. Для
-- таких площадок есть режим UPLOADS_DRIVER=database — тогда содержимое файла
-- лежит в этой колонке.
--
-- Колонка nullable: у вложений, сохраненных на диск, она остается пустой.
-- ---------------------------------------------------------------------------

ALTER TABLE chat_attachments
  ADD COLUMN IF NOT EXISTS content bytea;

-- Хранилище видно по тому, заполнено ли содержимое: путь на диске и байты в
-- базе одновременно не используются.
COMMENT ON COLUMN chat_attachments.content IS
  'Содержимое файла при UPLOADS_DRIVER=database. NULL — файл лежит на диске по storage_path.';
