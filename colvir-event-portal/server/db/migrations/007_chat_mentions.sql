-- ---------------------------------------------------------------------------
-- Упоминания сотрудников в чате.
--
-- Упоминания хранятся отдельной таблицей, а не разбором текста сообщения при
-- показе. Разбор по имени был бы ненадежен: тезки, смена фамилии, запятая
-- сразу после имени — и подсветка с уведомлением начали бы расходиться.
-- Здесь же связь с конкретной учетной записью зафиксирована на момент отправки.
--
-- Составной первичный ключ заодно защищает от повторов: упомянуть одного и того
-- же человека дважды в одном сообщении можно, но записи будет две одинаковых
-- и уведомлений тоже — чего быть не должно.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS chat_mentions (
  message_id   text NOT NULL REFERENCES chat_messages (id) ON DELETE CASCADE,
  user_id      uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  display_name text NOT NULL,
  PRIMARY KEY (message_id, user_id)
);

-- «Где меня упоминали» — выборка по сотруднику.
CREATE INDEX IF NOT EXISTS chat_mentions_user_idx
  ON chat_mentions (user_id);

-- Поиск коллег для подсказки идет по имени без учета регистра.
CREATE INDEX IF NOT EXISTS users_display_name_lower_idx
  ON users (lower(display_name));
